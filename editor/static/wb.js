const WB_K_MIN = 2500, WB_K_MAX = 10000, WB_K_STEP = 10, WB_FINE = 14;
const WB_DEFAULT_CAL = [1.684, 3.0558];

// KelvinWB from a DNG: [{k, r, b}] (r, b as stored, 8192 = 1.0) or null
function parseKelvinWB(buf) {
  const u8 = new Uint8Array(buf);
  const sig = [0x52, 0x49, 0x43, 0x4f, 0x48, 0x00, 0x49, 0x49];   // "RICOH\0II"
  let base = -1;
  for (let i = 0; i + 8 <= u8.length && base < 0; i++) {
    if (u8[i] !== 0x52) continue;
    let ok = true;
    for (let j = 1; j < 8 && ok; j++) ok = u8[i + j] === sig[j];
    if (ok) base = i;
  }
  if (base < 0) return null;
  const dv = new DataView(buf);
  const u16 = (o) => dv.getUint16(o, true), u32 = (o) => dv.getUint32(o, true);
  try {
    const ifd = base + 8, n = u16(ifd);
    for (let e = 0; e < n; e++) {
      const p = ifd + 2 + 12 * e;
      if (u16(p) !== 0x0221) continue;
      const len = u32(p + 4);
      const at = base + u32(p + 8);
      if (len < 2 || at + len > u8.length) return null;
      const cnt = u16(at), out = [];
      for (let k = 0; k < cnt && 2 + 8 * k + 8 <= len; k++) {
        const q = at + 2 + 8 * k;
        out.push({ k: 53190 - u16(q), r: u16(q + 4), b: u16(q + 6) });
      }
      return out.length ? out : null;
    }
  } catch { /* not a readable makernote */ }
  return null;
}

// [R, B] calibration factors: gain = table value * factor / 8192
function wbCalibration(kwb) {
  const pts = (kwb || []).filter((p) => p.k >= WB_K_MIN && p.k <= WB_K_MAX && (p.k - WB_K_MIN) % WB_K_STEP === 0);
  if (pts.length < 2) return WB_DEFAULT_CAL.slice();
  const idx = (p) => (p.k - WB_K_MIN) / WB_K_STEP;
  const mean = (f) => pts.reduce((s, p) => s + f(p), 0) / pts.length;
  return [mean((p) => p.r / WB_R[idx(p)]), mean((p) => p.b / WB_B[idx(p)])];
}

// camera gains [R, G, B] (G = 1) for colour temperature k and fine steps ab, gm
// (-14..+14; + is amber resp. magenta)
function wbGainsKelvin(k, ab, gm, cal) {
  const i = Math.round((Math.min(WB_K_MAX, Math.max(WB_K_MIN, k)) - WB_K_MIN) / WB_K_STEP);
  const a = Math.min(28, Math.max(0, Math.round(ab) + WB_FINE));
  const g = Math.min(28, Math.max(0, Math.round(gm) + WB_FINE));
  const fr = (WB_GM_R[g] * WB_AB_R[a]) >> 13, fb = (WB_GM_B[g] * WB_AB_B[a]) >> 13;
  const r = (WB_R[i] * fr) >> 13, b = (WB_B[i] * fb) >> 13;
  return [r * cal[0] / 8192, 1, b * cal[1] / 8192];
}

// colour temperature and G-M step that come closest to gains [R, G, B]
// (A-B at 0); used as the starting point of the controls
function wbEstimate(wb, cal) {
  const r = Math.log(wb[0] / cal[0] * 8192), b = Math.log(wb[2] / cal[1] * 8192);
  let best = { k: 5200, gm: 0 }, err = Infinity;
  for (let gm = -WB_FINE; gm <= WB_FINE; gm++) {
    const fr = (WB_GM_R[gm + WB_FINE] * WB_AB_R[WB_FINE]) >> 13, fb = (WB_GM_B[gm + WB_FINE] * WB_AB_B[WB_FINE]) >> 13;
    for (let i = 0; i < WB_R.length; i++) {
      const dr = Math.log((WB_R[i] * fr) >> 13) - r, db = Math.log((WB_B[i] * fb) >> 13) - b;
      const e = dr * dr + db * db;
      if (e < err) { err = e; best = { k: WB_K_MIN + WB_K_STEP * i, gm }; }
    }
  }
  return best;
}
